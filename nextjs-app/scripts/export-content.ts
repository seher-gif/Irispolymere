/**
 * Reads the local admin database (SQLite, edited via /admin) and
 * regenerates the site's static content data files. Run this after
 * publishing changes in the admin panel, then `npm run build` + redeploy
 * so the live site picks them up.
 */
import { PrismaClient } from "../lib/generated/prisma/client";
import { PrismaLibSql } from "@prisma/adapter-libsql";
import { writeFile } from "fs/promises";
import path from "path";

const dbPath = path.join(process.cwd(), "dev.db");
const adapter = new PrismaLibSql({ url: `file:${dbPath}` });
const prisma = new PrismaClient({ adapter });

function esc(str: string) {
  return str.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

function tri(en: string, fr: string | null, ar: string | null) {
  return `{ en: \`${esc(en)}\`, fr: \`${esc(fr || en)}\`, ar: \`${esc(ar || en)}\` }`;
}

const SITE_SUFFIX = " — Iris Polymere";
const META_TITLE_TARGET = 60;

// Only append the site name to an auto-generated fallback title when it still
// fits within the ~60-char recommended <title> length; a long post title is
// better left bare than truncated or pushed past the SEO-recommended length.
function withBrandSuffix(title: string) {
  return title.length + SITE_SUFFIX.length <= META_TITLE_TARGET ? `${title}${SITE_SUFFIX}` : title;
}

async function main() {
  const posts = await prisma.post.findMany({
    where: { published: true },
    include: { category: true },
    orderBy: { publishedAt: "desc" },
  });

  const certificates = await prisma.certificate.findMany({ orderBy: { key: "asc" } });
  const pageMetas = await prisma.pageMeta.findMany();
  const banners = await prisma.banner.findMany({ orderBy: { order: "asc" } });

  const blogEntries = posts.map((p) => {
    const category = p.category
      ? tri(p.category.nameEn, p.category.nameFr, p.category.nameAr)
      : "null";
    // SEO fields fall back to title / excerpt per-locale when left blank.
    // A custom meta title is used verbatim (it's the final <title>, same as
    // WordPress SEO plugins); only the auto-generated fallback gets the
    // site name appended, since the raw post title never includes it.
    const metaTitle = tri(
      p.metaTitleEn || withBrandSuffix(p.titleEn),
      p.metaTitleFr || withBrandSuffix(p.titleFr || p.titleEn),
      p.metaTitleAr || withBrandSuffix(p.titleAr || p.titleEn)
    );
    const metaDescription = tri(
      p.metaDescriptionEn || p.excerptEn,
      p.metaDescriptionFr || p.excerptFr,
      p.metaDescriptionAr || p.excerptAr
    );
    return `  {
    slug: ${JSON.stringify(p.slug)},
    categoryName: ${category},
    title: ${tri(p.titleEn, p.titleFr, p.titleAr)},
    excerpt: ${tri(p.excerptEn, p.excerptFr, p.excerptAr)},
    bodyHtml: ${tri(p.bodyEn, p.bodyFr, p.bodyAr)},
    metaTitle: ${metaTitle},
    metaDescription: ${metaDescription},
    coverImage: ${p.coverImage ? JSON.stringify(p.coverImage) : "null"},
    publishedAt: ${JSON.stringify((p.publishedAt ?? p.createdAt).toISOString())},
  }`;
  });

  const blogFile = `// Auto-generated by \`npm run export-content\` — do not edit by hand.
// Source of truth: the local admin database (/admin). Re-run the export
// after publishing changes there, then rebuild and redeploy.

export type LocalizedText = { en: string; fr: string; ar: string };

export type BlogPost = {
  slug: string;
  categoryName: LocalizedText | null;
  title: LocalizedText;
  excerpt: LocalizedText;
  bodyHtml: LocalizedText;
  metaTitle: LocalizedText;
  metaDescription: LocalizedText;
  coverImage: string | null;
  publishedAt: string;
};

export const blogPosts: BlogPost[] = [
${blogEntries.join(",\n")}
];

export const blogPostsBySlug: Record<string, BlogPost> = Object.fromEntries(
  blogPosts.map((p) => [p.slug, p])
);
`;

  const certEntries = certificates.map((c) => {
    return `  {
    key: ${JSON.stringify(c.key)},
    title: ${tri(c.titleEn, c.titleFr, c.titleAr)},
    desc: ${tri(c.descEn, c.descFr, c.descAr)},
    pdfUrl: ${c.pdfUrl ? JSON.stringify(c.pdfUrl) : "null"},
  }`;
  });

  const certFile = `// Auto-generated by \`npm run export-content\` — do not edit by hand.
// Source of truth: the local admin database (/admin/certificates).

import type { LocalizedText } from "./blog";

export type CertificateData = {
  key: string;
  title: LocalizedText;
  desc: LocalizedText;
  pdfUrl: string | null;
};

export const certificates: CertificateData[] = [
${certEntries.join(",\n")}
];
`;

  const pageMetaEntries = pageMetas.map((p) => {
    const field = (v: string | null) => (v ? JSON.stringify(v) : "null");
    return `  ${JSON.stringify(p.key)}: {
    metaTitleEn: ${field(p.metaTitleEn)}, metaTitleFr: ${field(p.metaTitleFr)}, metaTitleAr: ${field(p.metaTitleAr)},
    metaDescriptionEn: ${field(p.metaDescriptionEn)}, metaDescriptionFr: ${field(p.metaDescriptionFr)}, metaDescriptionAr: ${field(p.metaDescriptionAr)},
  }`;
  });

  const pageMetaFile = `// Auto-generated by \`npm run export-content\` — do not edit by hand.
// Source of truth: the local admin database (/admin/pages). Re-run the
// export after publishing changes there, then rebuild and redeploy.

export type PageMetaOverride = {
  metaTitleEn: string | null;
  metaTitleFr: string | null;
  metaTitleAr: string | null;
  metaDescriptionEn: string | null;
  metaDescriptionFr: string | null;
  metaDescriptionAr: string | null;
};

export const pageMetaOverrides: Record<string, PageMetaOverride> = {
${pageMetaEntries.join(",\n")}
};
`;

  const bannerEntries = banners.map((b) => {
    return `  { url: ${JSON.stringify(b.url)}, altText: ${b.altText ? JSON.stringify(b.altText) : "null"} }`;
  });

  const bannersFile = `// Auto-generated by \`npm run export-content\` — do not edit by hand.
// Source of truth: the local admin database (/admin/banners). Re-run the
// export after publishing changes there, then rebuild and redeploy.

export type Banner = { url: string; altText: string | null };

export const banners: Banner[] = [
${bannerEntries.join(",\n")}
];
`;

  await writeFile(path.join(process.cwd(), "lib/data/blog.ts"), blogFile, "utf-8");
  await writeFile(path.join(process.cwd(), "lib/data/certificates.ts"), certFile, "utf-8");
  await writeFile(path.join(process.cwd(), "lib/data/page-meta.ts"), pageMetaFile, "utf-8");
  await writeFile(path.join(process.cwd(), "lib/data/banners.ts"), bannersFile, "utf-8");

  console.log(`Exported ${posts.length} published post(s), ${certificates.length} certificate(s), ${pageMetas.length} page meta override(s), ${banners.length} banner(s).`);
  console.log("Wrote lib/data/blog.ts, lib/data/certificates.ts, lib/data/page-meta.ts and lib/data/banners.ts");
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
